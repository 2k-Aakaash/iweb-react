// Frontier World: an original frontier landscape to listen to, as data only (World →
// Destination → Location → layers). Nothing here plays sound: environments.js turns each
// location into an environment the Atmosphere engine plays, from the shared sound library
// (sounds.js), the living-world events (events.js) and the generated music (music.js).
//
// Every name and description is original to iWeb (a test checks for names from any game).
// Every sound is synthesized live in the browser: no recordings and nothing to license yet.
// The record format already has room for licensed recordings (assets.js), unused for now.
//
//   destination (a region in code: `regionId`)
//     { id, name, description, palette: [a, b], accent, glow: [3], terrain,
//       weather: { allowed, weights, dwell: [min, max] simulated minutes } }
//   location
//     { id, regionId, name, description, identity, tags,
//       time, weather,                 its own hour and weather (the defaults)
//       character: { water, wind, vegetation },
//       scenery: { features },         what the artwork draws
//       layers: [{ id, kind, variant, label, level, source }],
//       events: [eventId],             its living-world pool (cooldowns: events.js)
//       moods: [moodId] }              music moods that suit it (music.js)
//
// A layer's `kind` is its sound (sounds.js) and its category for time and weather
// (conditions.js); `variant` picks the flavour; `level` is the curated starting mix (0–1).
// `source` says where its sound comes from: { kind: 'synth', recipe } today.

